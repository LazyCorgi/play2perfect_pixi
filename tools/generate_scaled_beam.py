"""Generate independent physical beam assets and matching train/eval YAML."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from evaluation.beam_scaling import problem_name
from tools.urdf_scaling import scaled_urdf


def generate(percent):
    name = problem_name(percent)
    s = percent / 100
    beam = ROOT / 'assets/urdf/fabrica/beam_3x'
    directory = beam / f'scale_{percent:03d}'
    config = ROOT / f'isaacsimenvs/cfg/task/PreciseAssemblyBeamScale{percent:03d}.yaml'
    if directory.exists() or config.exists():
        raise FileExistsError(f'Existing size artifacts: {directory} / {config}')
    pairs = [(beam / '2/sdf_hybrid/beam_3x_2_matchedmass_sdf_hybrid.urdf', 'object.urdf'),
             (beam / 'insertion_fixtures/part_2_sdf_hybrid.urdf', 'fixture.urdf')]
    # Validate inputs before creating any output.
    trees = [(source, target, scaled_urdf(source, s, destination=directory / target)) for source, target in pairs]
    cfg = yaml.safe_load((ROOT / 'isaacsimenvs/cfg/task/PreciseAssembly.yaml').read_text())
    cfg['scene']['num_envs'] = 96
    cfg['precise_assembly'].update(problem=name, insertion_success_tolerance=.01*s, retract_success_tolerance=.005*s)
    cfg['reward']['fixed_size'] = [v*s for v in cfg['reward']['fixed_size']]
    # Capacity reservations only; retain solver, time step and contact behavior.
    cfg['sim']['physx'].update(gpu_found_lost_aggregate_pairs_capacity=131072,
                             gpu_total_aggregate_pairs_capacity=262144,
                             gpu_max_rigid_contact_count=524288,
                             gpu_max_rigid_patch_count=131072,
                             gpu_collision_stack_size=134217728)
    directory.mkdir()
    for source, target, tree in trees:
        tree.getroot().set('name', f'{source.stem}_scale_{percent:03d}')
        tree.write(directory / target, encoding='utf-8', xml_declaration=True)
    metadata = {'problem': name, 'source_problem': 'beam_assembly_step1', 'linear_scale': s,
                'mass_scale': s**3, 'inertia_scale': s**5, 'mass_assumption': 'constant density; not hardware validated',
                'source_sha256': {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p, _ in pairs},
                'task_config': str(config.relative_to(ROOT)), 'goal_mode': 'preInsertAndFinal',
                'standard_goal_xy_noise_m': .002}
    (directory / 'metadata.json').write_text(json.dumps(metadata, indent=2)+'\n')
    config.write_text('# Generated by tools/generate_scaled_beam.py; lengths relative to released beam assets.\n'+yaml.safe_dump(cfg, sort_keys=False))
    return metadata


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--percent', type=int, required=True)
    args = parser.parse_args()
    print(json.dumps(generate(args.percent), indent=2))
